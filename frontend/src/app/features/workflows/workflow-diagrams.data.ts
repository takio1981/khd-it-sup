/**
 * เนื้อหาผังการทำงานระบบ (SOP) ทั้งหมด — ต้องตรงกับพฤติกรรมจริงของโค้ด (backend/src/modules/*) เสมอ
 * อัปเดตไฟล์นี้ทุกครั้งที่กระบวนการ/ขั้นตอน/การรับ-ส่งข้อมูลของระบบเปลี่ยน (ดู CLAUDE.md)
 *
 * รูปแบบการเขียนผัง (mermaid flowchart):
 * - เส้นเชื่อม 1 เส้นต่อ 1 บรรทัดเสมอ (ห้ามเขียนต่อกันเป็นสาย A --> B --> C หรือใช้ &) เพราะ component เติม id/แอนิเมชัน
 *   และสีเส้น "ไม่ผ่าน" ให้อัตโนมัติจากการอ่านทีละบรรทัด
 * - `-->` = ลำดับขั้นตอนหลัก, `-.->` = ผลข้างเคียง/แจ้งเตือน/ทางเลือก, `<-->` = รับ-ส่งข้อมูลสองทาง
 * - ทุกโหนดใส่คลาสผู้รับผิดชอบ: :::user / :::staff / :::tech / :::sys / :::ext / :::store / :::decide / :::start / :::blocked
 */

export type SopActor = 'user' | 'staff' | 'tech' | 'sys' | 'ext' | 'store' | 'decide' | 'start' | 'blocked';

export interface ISopStep {
  actor: SopActor;
  who: string;
  action: string;
  output: string;
  sla?: string;
}

export interface IWorkflowSection {
  key: string;
  title: string;
  short: string;
  icon: string;
  description: string;
  definition?: string;
  steps?: ISopStep[];
  notes: string[];
}

export interface IDataExchangeRow {
  from: string;
  to: string;
  data: string;
  channel: string;
  when: string;
}

export interface IRoleMatrixRow {
  role: string;
  viewTickets: string;
  editTickets: string;
  adminAccess: string;
}

